"""Build dual-style PNG+TXT copies, preserving all source masters and whole-group holdout."""
from pathlib import Path
import csv,hashlib,json,collections
from PIL import Image
AI=Path(__file__).resolve().parents[1]
ROOT=AI.parent
OUT=AI/'draw-things/full-v1'
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
    old=AI/'dataset/texture-v1'
    config=json.loads((OUT/'caption-source.json').read_text())
    rows=list(csv.DictReader((old/'training_manifest.csv').open()))
    accepted=json.loads((old/'owner_acceptance.json').read_text())
    acceptance={(r['code'],r['style']):r for r in accepted}
    for r in accepted:assert sha(ROOT/r['source_path'])==r['sha256'],r['source_path']
    priorchecks=json.loads((old/'checks.json').read_text())
    for path,digest in priorchecks['input_csv_sha256'].items():assert sha(Path(path))==digest
    hold=set(config['validation_groups']); records=[]
    for r in rows:
        split='validation' if r['similarity_group'] in hold or r['artifact_code'] in hold else 'train'
        if r['split']=='validation':assert split=='validation'
        for sty,srcstyle in [('flat','flat'),('textured','texture')]:
            source=ROOT/acceptance[(r['code'],srcstyle)]['source_path']
            target=OUT/('train' if split=='train' else 'validation-DO-NOT-TRAIN')/(r['code']+'_'+sty+'.png');target.parent.mkdir(parents=True,exist_ok=True)
            with Image.open(source) as src:
                rgba=src.convert('RGBA');bbox=rgba.getchannel('A').getbbox();assert bbox
                crop=rgba.crop(bbox);scale=min(840/crop.width,840/crop.height);size=tuple(max(1,round(v*scale)) for v in crop.size);crop=crop.resize(size,Image.Resampling.LANCZOS)
                canvas=Image.new('RGBA',(1024,1024),'white');offset=((1024-size[0])//2,(1024-size[1])//2);canvas.alpha_composite(crop,offset)
                # Existing outputs are verified against regenerated bytes before any mutation.
                import io
                buf=io.BytesIO();canvas.convert('RGB').save(buf,format='PNG');data=buf.getvalue()
                if target.exists():assert target.read_bytes()==data,'Edited output: '+str(target)
                else:target.write_bytes(data)
            visual=config['flat_visual'][r['code']] if sty=='flat' else r['caption'].removeprefix('tptrx, isolated ornamental motif, ').removesuffix(', centered on a white background.')
            caption=f"tptrx, {config['style_labels'][sty]}, {visual}, centered on a white background.\n"
            txt=target.with_suffix('.txt')
            if txt.exists():assert txt.read_text()==caption,'Edited caption: '+str(txt)
            else:txt.write_text(caption)
            records.append({'code':r['code'],'style':sty,'artifact_code':r['artifact_code'],'similarity_group':r['similarity_group'],'split':split,'source_path':str(source.relative_to(ROOT)),'source_sha256':sha(source),'png_path':str(target.relative_to(AI)),'png_sha256':sha(target),'caption_sha256':sha(txt),'caption':caption.strip(),'alpha_bbox':bbox,'resize':size,'offset':offset,'prior_pilot_split':r['split']})
    for key in ['code','artifact_code','similarity_group']:
        a={r[key] for r in records if r['split']=='train'};b={r[key] for r in records if r['split']=='validation'};assert not a&b,key
    counts=collections.Counter((r['split'],r['style']) for r in records)
    assert len(records)==220 and counts[('train','flat')]==99 and counts[('validation','flat')]==11
    for folder in ['train','validation-DO-NOT-TRAIN']:
        selected=[r for r in records if r['split']==('train' if folder=='train' else 'validation')]
        expected={Path(r['png_path']).name for r in selected}|{Path(r['png_path']).with_suffix('.txt').name for r in selected}
        assert {p.name for p in (OUT/folder).iterdir()}==expected
        for r in selected:
            with Image.open(AI/r['png_path']) as im:assert im.mode=='RGB' and im.size==(1024,1024) and im.getpixel((0,0))==(255,255,255)
    with (OUT/'manifest.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(records[0]));w.writeheader();w.writerows(records)
    with (OUT/'captions.csv').open('w',newline='') as f:
        w=csv.writer(f);w.writerow(['filename','split','style','caption']);w.writerows([Path(r['png_path']).name,r['split'],r['style'],r['caption']] for r in records)
    result={'status':'PASSED','train_images':198,'train_motifs':99,'train_artifacts':len({r['artifact_code'] for r in records if r['split']=='train'}),'validation_images':22,'validation_motifs':11,'validation_artifacts':4,'holdout_groups':sorted(hold),'masters_verified':220,'pair_artifact_similarity_leakage':False,'style_balance':'99 flat + 99 textured train; 11+11 validation','training_executed':False,'caption_source_sha256':sha(OUT/'caption-source.json'),'manifest_sha256':sha(OUT/'manifest.csv'),'scope':'joint style selection is experimental, not yet validated','holdout_note':'Original validation artifact held out with all reserve siblings; two additional unseen pilot-out-of-scope groups held out. Original fiber validation was already observed, not a pristine final test.'}
    (OUT/'checks.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n');print(json.dumps(result,ensure_ascii=False,indent=2))
if __name__=='__main__':main()
